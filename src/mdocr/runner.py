"""Durable execution and publication for frozen mdocr plans."""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
import tempfile
import time
from pathlib import Path

from . import __version__
from .markdown import IMAGE_RE


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".mdocr-run-", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def _save(path: Path, state: dict) -> None:
    _atomic(path, (json.dumps(state, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode())


def _block(image: dict, mode: str, body: str) -> str:
    identifier = image["id"]
    digest = image["sha256"]
    original = image["original_link"]
    # Metadata is entirely generated by this module; source links remain ordinary Markdown.
    return (f'<!-- mdocr:ocr-begin v=2 id={identifier} -->\n'
            f'<!-- mdocr:meta mode={mode} sha256={digest} -->\n'
            f'> Original image: [{image["resource_id"]}]({original})\n\n'
            f'{body.strip()}\n<!-- mdocr:ocr-end -->')


def run_command(args) -> int:
    from .plan import read_plan

    plan_path = Path(args.plan).resolve(strict=True)
    result_path = Path(args.result).resolve()
    plan = read_plan(plan_path)
    settings, documents = plan["settings"], plan["documents"]
    digest = _sha(plan_path.read_bytes())
    sources, outputs = set(), set()
    for doc in documents:
        source, output = Path(doc["path"]).resolve(strict=True), Path(doc["output"]).resolve()
        if source in sources or output in outputs:
            raise ValueError("duplicate source or output in plan")
        sources.add(source); outputs.add(output)
        if output == source or source in output.parents:
            raise ValueError("output overlaps source")
        raw = source.read_bytes()
        if _sha(raw) != doc["sha256"]:
            raise ValueError(f"SOURCE_DRIFT: {source}")
        if not source.is_file():
            raise ValueError(f"invalid source: {source}")
        for image in doc["images"]:
            if image.get("selected") and not image.get("error"):
                path = Path(image["source_path"])
                if not path.is_file() or _sha(path.read_bytes()) != image["sha256"]:
                    raise ValueError(f"IMAGE_DRIFT: {path}")
    if result_path in sources | outputs or result_path == plan_path or plan_path in outputs:
        raise ValueError("result, plan, source, and output paths must be distinct")
    lockpath = plan_path.with_name(plan_path.name + ".lock")
    lockpath.parent.mkdir(parents=True, exist_ok=True)
    with lockpath.open("a+b") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise ValueError("plan is already being executed") from exc
        return _execute(plan, plan_path, result_path, digest, args)


def _execute(plan: dict, plan_path: Path, result_path: Path, digest: str, args) -> int:
    from .paddle import PaddleClient

    state = {"schema_version": "mdocr-result-2", "plan_sha256": digest,
             "status": "running", "causes": [], "concurrency": plan["settings"].get("concurrency", 3),
             "budget": {"requests": 0, "tokens": 0, "reserved_tokens": 0}, "requests": [], "documents": []}
    if result_path.exists():
        old = json.loads(result_path.read_text(encoding="utf-8"))
        if old.get("plan_sha256") != digest:
            raise ValueError("result is owned by a different plan")
        state = old
        # Never replay a previously admitted request without a recorded terminal outcome.
        unknown = {r["key"] for r in state.get("requests", []) if r.get("status") in {"admitted", "unknown"}}
    else:
        unknown = set()
    client = None
    if plan["settings"]["mode"] == "paddle":
        token = os.environ.get("PADDLEOCR_TOKEN")
        if not token:
            raise ValueError("PADDLEOCR_TOKEN is required")
        client = PaddleClient(token, endpoint=plan["settings"].get("endpoint"))
    else:
        # Import only at the point LLM execution is requested; Paddle/help remain independent.
        from .llm import LlmClient
        client = LlmClient(plan["settings"]["model"], plan["settings"]["effort"])
        client.preflight()
    completed = []
    for doc in plan["documents"]:
        source = Path(doc["path"])
        text = source.read_bytes().decode("utf-8")
        resources, patches = [], {}
        selected = [im for im in doc["images"] if im.get("selected")]
        if plan["settings"]["mode"] == "llm" and selected:
            key = f'{doc["document_id"]}:llm'
            if key in unknown:
                resources = [{"id": im["id"], "resource_id": im["resource_id"], "status": "unknown", "reason": "OUTCOME_UNKNOWN"} for im in selected]
            else:
                request = {"key": key, "status": "admitted", "reserved_tokens": 0}
                state["requests"].append(request); state["budget"]["requests"] += 1
                _save(result_path, state)  # durable admission precedes provider call
                try:
                    response = client.convert(text, [{"id": im["id"], "path": im["source_path"]} for im in selected], plan["settings"]["prompt"])
                    by_id = {p["id"]: p for p in response["patches"]}
                    if len(by_id) != len(response["patches"]) or set(by_id) != {im["id"] for im in selected}:
                        raise ValueError("invalid patch IDs")
                    patches = {im["id"]: by_id[im["id"]]["markdown"] for im in selected}
                    state["budget"]["tokens"] += response.get("usage_tokens") or 0
                    request.update(status="success", usage_tokens=response.get("usage_tokens"))
                except Exception as exc:
                    status = getattr(exc, "status", None)
                    request.update(status="failed" if status is not None else "unknown", reason=getattr(exc, "reason", "LLM_REQUEST_FAILED"))
                    resources = [{"id": im["id"], "resource_id": im["resource_id"], "status": request["status"], "reason": request["reason"]} for im in selected]
                _save(result_path, state)
        for image in doc["images"]:
            if any(r.get("id") == image["id"] for r in resources):
                continue
            status, reason, body = "unselected", None, None
            if image.get("selected"):
                key = f'{doc["document_id"]}:{image["id"]}'
                if key in unknown:
                    status, reason = "unknown", "OUTCOME_UNKNOWN"
                elif image.get("error"):
                    status, reason = "failed", image["error"]
                else:
                    try:
                        state["requests"].append({"key": key, "status": "admitted"})
                        state["budget"]["requests"] += 1; _save(result_path, state)
                        if settings["mode"] == "paddle":
                            body = client.convert(Path(image["source_path"]))
                        else:
                            body = patches[image["id"]]
                        state["requests"][-1].update(status="success")
                        status = "success"
                    except Exception as exc:
                        state["requests"][-1].update(status="failed", reason=str(exc))
                        status, reason = "failed", "CONVERSION_FAILED"
            resources.append({"id": image["id"], "resource_id": image["resource_id"], "status": status, **({"reason": reason} if reason else {})})
            if body is not None:
                image["_body"] = body
        complete = all(r["status"] == "success" for r in resources) and len(resources) == len(doc["images"])
        out = None
        if complete:
            replacements = []
            for image in doc["images"]:
                replacements.append((image["start"], image["end"], _block(image, settings["mode"], image.pop("_body"))))
            for start, end, replacement in reversed(replacements):
                text = text[:start] + replacement + text[end:]
            out = Path(doc["output"])
            _atomic(out, text.encode("utf-8"))
            completed.append(out)
        state["documents"].append({"document_id": doc["document_id"], "path": doc["path"], "status": "completed" if complete else "partial", "output": str(out) if out else None, "resources": resources})
        _save(result_path, state)
    state["status"] = "completed" if all(d["status"] == "completed" for d in state["documents"]) else "partial"
    _save(result_path, state)
    return 0 if state["status"] == "completed" else 2
